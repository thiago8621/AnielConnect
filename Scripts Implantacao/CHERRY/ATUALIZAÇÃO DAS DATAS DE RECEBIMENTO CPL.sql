EXECUTE BLOCK
AS
    declare variable VCODCT VARCHAR(4);
    declare variable VPROJETO VARCHAR(20);
    declare variable VCODMAT VARCHAR(12);
    declare variable VCODCPL VARCHAR(100);
    declare variable VNOTA VARCHAR(15);
    declare variable VDATA DM_DATA;
BEGIN

FOR
    SELECT A.CODCT, A.PROJETO, A.CODMAT, A.CODCPL
    FROM TB_CODIGO_COMPLEMENTAR A
    INNER JOIN TB_MATERIAL B ON (A.CODMAT = B.CODMAT)
    WHERE B.SUBCOD = 'S'
          AND B.SUBCOD_EXCLUSIVO = 'S'
          AND COALESCE(A.CODCPL,'')<>''
          AND A.DATA_NF_RECEB IS NULL
    INTO :VCODCT, :VPROJETO, :VCODMAT, :VCODCPL
DO
  BEGIN
     SELECT FIRST 1 C.DATA, C.NOTAFISCAL
     FROM TB_ESTOQUE C
     WHERE C.SEQLIVRE = '-' AND C.NOTAFISCAL <> '-' AND C.CODCT = :VCODCT
       AND C.PROJETO = :VPROJETO AND C.CODMAT = :VCODMAT AND C.CODCPL = :VCODCPL AND C.ENTRADA > 0
     INTO :VDATA, :VNOTA;

     if (:VDATA IS NOT NULL) then
     BEGIN
       UPDATE TB_CODIGO_COMPLEMENTAR D SET D.DATA_NF_RECEB = :VDATA, D.NOTAFISCAL_RECEB = :VNOTA
       WHERE D.CODCT = :VCODCT AND D.PROJETO = :VPROJETO AND D.CODMAT=:VCODMAT AND D.CODCPL=:VCODCPL;
     END
  END
END
