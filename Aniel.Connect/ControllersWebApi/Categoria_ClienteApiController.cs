        [HttpPost()]
        [Route("api/categoria_clienteapi/GetAll")]
        public async Task<DataTableResponse<Categoria_ClienteListaModel>> GetAll(Categoria_Cliente_DataTableRequest request)
        {
            List<Categoria_ClienteListaModel> retorno = new List<Categoria_ClienteListaModel>();
            IOrderedEnumerable<Categoria_ClienteListaModel> listaOrdenada = null;
            Int32 recordsTotal = 0;

            using (ISession session = HibernateUtil.GetSession())
            {

                Dictionary<String, Object> parametros = new Dictionary<string, object>();

                //Count
                using (var com = session.Connection.CreateCommand())
                {
                    StringBuilder sql = new StringBuilder("SELECT COUNT(ID) CO FROM TB_CATEGORIA_CLIENTE");

                    using (var reader = await CommandHelper.ExecuteReader(com, sql, parametros, session.Connection, null))
                    {
                        if (await reader.ReadAsync())
                        {
                            recordsTotal = Convert.ToInt32(reader["CO"]);
                        }
                    }
                }

                //Select
                using (var com = session.Connection.CreateCommand())
                {

                    StringBuilder sql = new StringBuilder();

                    sql.AppendLine(" SELECT A.ID, A.DESCRICAO, A.STATUS "); 
                    sql.AppendLine(" FROM TB_CATEGORIA_CLIENTE A ");
                    

                    //Filtrando
                    if (!String.IsNullOrEmpty(request.search.value))
                    {
                        sql.AppendLine("WHERE ((UPPER(A.DESCRICAO) LIKE UPPER(@SEARCH))) ");
                        parametros.Add("@SEARCH", String.Format("%{0}%", request.search.value));
                    }


                    //Busca com paginacao
                    using (var reader = await CommandHelper.ExecuteReader(com, sql, parametros, session.Connection, null))
                    {
                        while (await reader.ReadAsync())
                        {
                            retorno.Add(new Categoria_ClienteListaModel
                            {
                                Id = Convert.ToInt64(reader["ID"]),
                                Descricao = Convert.ToString(reader["DESCRICAO"]),
                                Status = HtmlEnumExtensions.GetEnumDescription<Status_Default>(Convert.ToString(reader["STATUS"]))
                            });
                        }
                    }

                }
            }

            //Ordenacao
            if (request.order != null && request.order.Any())
            {
                int sortColumnIndex = request.order[0].column;
                string sortDirection = request.order[0].dir;
                switch (sortColumnIndex)
                {
                    case 1:     // Descricao
                        {
                            if (sortDirection == "asc")
                                listaOrdenada = retorno.OrderBy(p => p.Id);
                            else
                                listaOrdenada = retorno.OrderByDescending(p => p.Id);
                            break;
                        }

                    case 2:     // Descricao
                        {
                            if (sortDirection == "asc")
                                listaOrdenada = retorno.OrderBy(p => p.Descricao);
                            else
                                listaOrdenada = retorno.OrderByDescending(p => p.Descricao);
                            break;
                        }

                    case 3:     // Descricao
                        {
                            if (sortDirection == "asc")
                                listaOrdenada = retorno.OrderBy(p => p.Status);
                            else
                                listaOrdenada = retorno.OrderByDescending(p => p.Status);
                            break;
                        }
                }
            }

            //Page e retornando DataTable
            return new DataTableResponse<Categoria_ClienteListaModel>
            {
                draw = request.draw,
                //recordsTotal = recordsTotal,
                recordsFiltered = recordsTotal,
                data = listaOrdenada,
                error = ""
            };

        }

        private Categoria_ClienteCadastroModel GetViewObj(Categoria_Cliente obj)
        {
            return new Categoria_ClienteCadastroModel
            {
                Id = obj.Id,
                Descricao = obj.Descricao,
                Tipo_Prioridade = obj.Tipo_Prioridade,
                Status = obj.Status == Status_Default.Ativo,
                Id_Cfop= obj.Id_Cfop,
                
                
                CodigoTipoClienteIntegracao = obj.CodigoTipoClienteIntegracao
            };
        }

        private void BindViewToObj(ISession session, ref Categoria_Cliente objBanco, Categoria_ClienteCadastroModel view)
        {
            objBanco.Descricao = view.Descricao;
            objBanco.Tipo_Prioridade = view.Tipo_Prioridade;
            if (objBanco.Id != 0)
            {
                objBanco.Status = view.Status ? Status_Default.Ativo : Status_Default.Inativo;
            }
            objBanco.Id_Cfop = Convert.ToInt32(view.Id_Cfop);

            objBanco.CodigoTipoClienteIntegracao = view.CodigoTipoClienteIntegracao;
        }

